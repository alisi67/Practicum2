rost=int(input())
tr=(ves/(rost)**2) * 703
if tr<16:
    print('выраженный дефицит массы тела')
elif 16<=tr<=18.49:
    print('недостаточная масса тела')
elif 18.5<=tr<=24.99:
    print('норма')
elif 24<=tr<=29.99:
    print('избыточная масса тела')
elif 30<=tr<=34.99:
    print('ожирение первой степени')
elif 35<=tr<=39.99:
    print('ожирение второй степени')
elif tr>=40:
    print('ожирение третьей степени')